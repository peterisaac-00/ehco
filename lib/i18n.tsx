const LanguageContext = createContext<LanguageContextValue | null>(null);

function interpolate(template: string, values?: TranslationValues) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? `{${name}}`));
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const { isAuthenticated } = useAuth();
  const [language, setLocalLanguage] = useState<AppLanguage>("ar");
  const [isReady, setIsReady] = useState(false);
  const languageQuery = trpc.preferences.language.useQuery(undefined, {
    enabled: isAuthenticated,
    retry: false,
    refetchOnMount: true,
  });
  const setLanguageMutation = trpc.preferences.setLanguage.useMutation();

  useEffect(() => {
    let active = true;
    void AsyncStorage.getItem(LANGUAGE_STORAGE_KEY).then((stored) => {
      if (!active) return;
      if (stored === "ar" || stored === "en") setLocalLanguage(stored);
      setIsReady(true);
    }).catch(() => setIsReady(true));
    return () => {
      active = false;
    };
  }, []);

  useEffect(() => {
    if (!isAuthenticated || (languageQuery.data !== "ar" && languageQuery.data !== "en")) return;
    setLocalLanguage(languageQuery.data);
    void AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, languageQuery.data);
  }, [isAuthenticated, languageQuery.data]);

  const setLanguage = useCallback(async (nextLanguage: AppLanguage) => {
    if (nextLanguage === language) return;
    const previousLanguage = language;
    setLocalLanguage(nextLanguage);
    try {
      if (isAuthenticated) await setLanguageMutation.mutateAsync(nextLanguage);
      await AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
      if (isAuthenticated) void languageQuery.refetch();
    } catch (error) {
      setLocalLanguage(previousLanguage);
      throw error;
    }
  }, [isAuthenticated, language, languageQuery, setLanguageMutation]);

  const t = useCallback<Translator>((key, values) => {
    const template = copy[language][key] ?? copy.ar[key] ?? key;
    return interpolate(template, values);
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    isRTL: language === "ar",
    isReady,
    setLanguage,
    t,
  }), [isReady, language, setLanguage, t]);

  return <LanguageContext.Provider value={value}><View style={{ flex: 1, direction: value.isRTL ? "rtl" : "ltr" }}>{children}</View></LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
